#!/usr/bin/env node
/**
 * Writes a build-time constant used for anything date-derived (years of
 * experience, role durations).
 *
 * Why a constant and not `new Date()` at runtime: the site is prerendered, so
 * the server renders at build time and the browser would render at visit time.
 * Computing from a shared frozen timestamp keeps both renders byte-identical
 * and avoids a hydration mismatch when a visit crosses a month boundary.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const now = new Date();
const iso = now.toISOString();

const contents = `// GENERATED FILE — do not edit. Regenerated by tools/generate-build-info.mjs.
export const BUILD_INFO = {
  /** ISO timestamp frozen at build time. */
  builtAt: '${iso}',
  /** Year-month the build ran, used for all duration arithmetic. */
  builtMonth: '${iso.slice(0, 7)}',
} as const;
`;

writeFileSync(join(root, 'src/environments/build-info.ts'), contents);
console.log(`build-info: ${iso}`);
